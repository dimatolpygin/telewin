#!/bin/sh
# Entrypoint приложения: сначала миграции, потом старт.
# Критерий этапа 0: миграции применяются автоматически, повторный старт не ломается
# (drizzle-kit migrate идемпотентен — уже применённые миграции пропускаются).
set -eu

echo "[entrypoint] Применяю миграции базы данных…"
npx drizzle-kit migrate

echo "[entrypoint] Миграции применены. Запускаю приложение…"
# exec — чтобы процесс приложения стал PID 1 и получал SIGTERM от docker stop
exec "$@"
