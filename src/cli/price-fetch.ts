/**
 * CLI: `npm run price:fetch`
 *
 * Один проход забора: взять самый свежий файл из источника (`.env`), скачать и
 * прогнать через импортёр этапа 2. Источник (FTP или локальная папка) и его
 * адрес — целиком в `.env`, смена адреса кода не требует.
 *
 * Коды выхода различают исходы для автоматики: 0 — обработан или брать нечего,
 * 2 — файл скачан, но отбит валидацией, 3 — файл ещё заливается (повторить позже).
 */
import { заборПрайса } from '../price/забор.js';
import { ОшибкаПрайса } from '../price/ошибки.js';
import { клиентPostgres } from '../db/index.js';
import { logger } from '../logger.js';

async function главная(): Promise<number> {
  const итог = await заборПрайса();

  switch (итог.исход) {
    case 'нет_файлов':
      logger.info('Забор завершён: в источнике нет прайсов.');
      return 0;

    case 'нет_нового':
      logger.info(`Забор завершён: новых файлов нет (последний — ${итог.имя}).`);
      return 0;

    case 'заливается':
      logger.warn(`Забор отложен: ${итог.имя} ещё заливается. Повторить позже.`);
      return 3;

    case 'обработан': {
      const и = итог.итог;
      if (и.исход === 'загружен') {
        logger.info(
          `Забор завершён: ${итог.имя} импортирован (#${и.importId}, позиций ${и.позиций.toLocaleString('ru-RU')}).`,
        );
        return 0;
      }
      if (и.исход === 'дубль') {
        logger.info(`Забор завершён: ${итог.имя} уже был в базе (импорт #${и.importId}, «${и.статус}»).`);
        return 0;
      }
      logger.error(`Забор завершён: ${итог.имя} ОТБИТ валидацией — ${и.причина}.`);
      logger.error('В базу ничего не записано, бот отвечает по прошлому прайсу.');
      return 2;
    }
  }
}

главная()
  .then(async (код) => {
    await клиентPostgres.end();
    process.exit(код);
  })
  .catch(async (причина: unknown) => {
    if (причина instanceof ОшибкаПрайса) {
      logger.error(`Не удалось разобрать прайс: ${причина.message}`);
      if (причина.подсказка !== undefined) logger.error(`Подсказка: ${причина.подсказка}`);
    } else {
      logger.error(`Забор не удался: ${причина instanceof Error ? причина.stack : String(причина)}`);
    }
    await клиентPostgres.end();
    process.exit(1);
  });
