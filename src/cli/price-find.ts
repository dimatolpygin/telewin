/**
 * CLI: `npm run price:find -- <текст>`
 *
 * Детерминированный поиск по текущему прайсу (этап 4): точное совпадение по
 * артикулу/штрихкоду, полнотекст, триграммы. Цена и остатки — из БД, обязаны
 * сходиться с прямым SQL. Дату актуальности печатаем всегда: ответ без неё —
 * полуправда. Остаток показываем по каждой точке отдельно.
 */
import { искать, type СпособСовпадения } from '../price/поиск.js';
import { клиентPostgres } from '../db/index.js';
import { logger } from '../logger.js';

const ПОДПИСЬ_СПОСОБА: Record<СпособСовпадения, string> = {
  артикул: 'точно по артикулу',
  штрихкод: 'точно по штрихкоду',
  название: 'по названию',
  похоже: 'похоже (возможна опечатка)',
};

function датаЧел(д: Date | null): string {
  return д === null ? 'неизвестно' : д.toLocaleString('ru-RU');
}

async function главная(): Promise<number> {
  const запрос = process.argv.slice(2).join(' ').trim();
  if (запрос === '') {
    console.error('Что искать? npm run price:find -- "болт м5"');
    return 1;
  }

  const начато = performance.now();
  const найденные = await искать(запрос);
  const мс = Math.round(performance.now() - начато);

  const строки: string[] = [];
  const п = (текст = '') => строки.push(текст);

  п();
  if (найденные.length === 0) {
    п(`По запросу «${запрос}» в текущем прайсе ничего не нашлось (${мс} мс).`);
  } else {
    п(`По запросу «${запрос}» найдено ${найденные.length} (${мс} мс):`);
    п();
    for (const товар of найденные) {
      const артикул = товар.артикул ? ` · арт. ${товар.артикул}` : '';
      п(`• «${товар.наименование}»${артикул} — ${товар.цена} руб. [${ПОДПИСЬ_СПОСОБА[товар.способ]}]`);
      for (const точка of товар.точки) {
        п(
          `    ${точка.магазин}: остаток ${точка.остаток} ${товар.единица ?? ''}`.trimEnd() +
            ` · данные от ${датаЧел(точка.данныеОт)}`,
        );
      }
      п(`    (общий по сети ${товар.остатокОбщий})`);
    }
  }
  п();
  console.log(строки.join('\n'));

  return 0;
}

главная()
  .then(async (код) => {
    await клиентPostgres.end();
    process.exit(код);
  })
  .catch(async (причина: unknown) => {
    logger.error(`Поиск не удался: ${причина instanceof Error ? причина.message : String(причина)}`);
    await клиентPostgres.end();
    process.exit(1);
  });
