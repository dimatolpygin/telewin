/**
 * CLI: `npm run price:find -- <текст>`
 *
 * Минимальный поиск по текущему снимку — подстрокой. Нужен, чтобы проверить
 * этап 2: что после отбитого импорта база продолжает отдавать прошлые хорошие
 * данные. Настоящий поиск (нормализация запроса покупателя, ранжирование,
 * «гвозди сотка» → «Гвоздь строительный 100») — этап 4.
 *
 * Дату актуальности печатаем всегда: ответ без неё — это полуправда.
 */
import { найтиВТекущем } from '../price/импорт.js';
import { клиентPostgres } from '../db/index.js';
import { logger } from '../logger.js';

async function главная(): Promise<number> {
  const запрос = process.argv.slice(2).join(' ').trim();
  if (запрос === '') {
    console.error('Что искать? npm run price:find -- "Болт M 5*12"');
    return 1;
  }

  const найденные = await найтиВТекущем(запрос);

  const строки: string[] = [];
  const п = (текст = '') => строки.push(текст);

  п();
  if (найденные.length === 0) {
    п(`По запросу «${запрос}» в текущем прайсе ничего не нашлось.`);
    п('Поиск идёт подстрокой по названию — на этапе 4 он станет умнее.');
  } else {
    п(`По запросу «${запрос}» найдено ${найденные.length}:`);
    for (const позиция of найденные) {
      п(
        `  ${позиция.магазин}: «${позиция.наименование}» · ${позиция.цена} руб. · ` +
          `остаток ${позиция.остаток} ${позиция.единица ?? ''} (общий по сети ${позиция.остатокОбщий}) · ` +
          `данные от ${позиция.данныеОт?.toLocaleString('ru-RU') ?? 'неизвестно'} (импорт #${позиция.importId})`,
      );
    }
  }
  п();
  console.log(строки.join('\n'));

  return 0;
}

главная()
  .then(async (код) => {
    await клиентPostgres.end();
    process.exit(код);
  })
  .catch(async (причина: unknown) => {
    logger.error(`Поиск не удался: ${причина instanceof Error ? причина.message : String(причина)}`);
    await клиентPostgres.end();
    process.exit(1);
  });
