/**
 * CLI: `npm run price:imports`
 *
 * Журнал импортов и свежесть по каждому магазину. Отвечает на два вопроса:
 * «что приезжало и чем закончилось» и «какими данными бот отвечает прямо сейчас».
 */
import { свежестьМагазинов, списокИмпортов } from '../price/импорт.js';
import { клиентPostgres } from '../db/index.js';
import { logger } from '../logger.js';

function датой(значение: Date | null): string {
  return значение === null ? '—' : значение.toLocaleString('ru-RU');
}

async function главная(): Promise<void> {
  const импорты = await списокИмпортов();
  const магазины = await свежестьМагазинов();

  const строки: string[] = [];
  const п = (текст = '') => строки.push(текст);

  п();
  п('Свежесть данных по магазинам (на это смотрит бот):');
  if (магазины.length === 0) {
    п('  Магазинов нет — ни одного удачного импорта ещё не было.');
  }
  for (const магазин of магазины) {
    if (магазин.importId === null) {
      п(`  ${магазин.название}: данных нет, текущий импорт не назначен`);
    } else {
      п(
        `  ${магазин.название}: импорт #${магазин.importId}, данные от ${датой(магазин.данныеОт)} ` +
          `· файл ${магазин.файл ?? '—'}`,
      );
    }
  }

  п();
  п(`Импорты (последние ${импорты.length}):`);
  if (импорты.length === 0) п('  Пусто.');

  for (const импорт of импорты) {
    const метка = импорт.статус === 'ok' ? 'ok  ' : 'ОТБИТ';
    п(
      `  #${импорт.id} [${метка}] ${импорт.файл} · позиций ${импорт.позиций.toLocaleString('ru-RU')} · ` +
        `${(импорт.размерБайт / 1024).toFixed(0)} КБ · ${импорт.раскладка} · файл от ${датой(импорт.файлОт)}`,
    );
    if (импорт.причинаОтказа !== null) п(`      причина отказа: ${импорт.причинаОтказа}`);
  }

  п();
  console.log(строки.join('\n'));
}

главная()
  .then(async () => {
    await клиентPostgres.end();
  })
  .catch(async (причина: unknown) => {
    logger.error(`Не удалось прочитать журнал импортов: ${причина instanceof Error ? причина.message : String(причина)}`);
    await клиентPostgres.end();
    process.exit(1);
  });
