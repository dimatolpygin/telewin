/**
 * CLI: `npm run price:parse -- <файл>`
 *
 * Печатает, что парсер увидел в файле: раскладку, число строк, примеры позиций
 * и статистику. Нужен, чтобы разбор прайса можно было проверить руками, не
 * поднимая базу и бота.
 */
import { разобратьПрайс, type Позиция, type РазборПрайса } from '../price/парсер.js';
import { ОшибкаПрайса } from '../price/ошибки.js';
import { logger } from '../logger.js';

/**
 * Ниже этого числа строк выгрузка похожа на неполную. Ориентир: боевой файл —
 * ~11 900 позиций, «пустышка» с FTP — 122. Это предупреждение, а не запрет:
 * решение «грузить или отбить» принимает валидатор импорта на этапе 2, у него
 * есть с чем сравнить — прошлый успешный импорт.
 */
const ПОДОЗРИТЕЛЬНО_МАЛО_СТРОК = 1000;

async function главная(): Promise<void> {
  const путь = process.argv[2];
  if (путь === undefined || путь.trim() === '') {
    console.error('Укажите файл прайса: npm run price:parse -- samples/boevoy_прайс_2026-07-08.xls');
    process.exit(1);
  }

  logger.info(`Разбираю прайс: ${путь}`);
  const начало = Date.now();
  const разбор = await разобратьПрайс(путь);
  logger.info(`Разбор закончен за ${Date.now() - начало} мс`);

  напечататьОтчёт(разбор);
}

function напечататьОтчёт(разбор: РазборПрайса): void {
  const строки: string[] = [];
  const п = (текст = '') => строки.push(текст);

  п();
  п(`Файл:              ${разбор.файл}`);
  п(`Размер:            ${(разбор.размерБайт / 1024 / 1024).toFixed(2)} МБ`);
  п(`Лист:              ${разбор.лист}`);
  п(`Раскладка:         ${разбор.раскладка.имя}`);
  п(`Определена по:     ширине строки и типам ячеек, совпало ${(разбор.доляСовпадения * 100).toFixed(1)}% строк выборки`);
  п(`Колонки:           ${разбор.раскладка.колонки.join(' · ')}`);
  п();
  п(`Строк с данными:   ${числом(разбор.строкСДанными)}`);
  п(`Разобрано позиций: ${числом(разбор.позиции.length)}`);
  п(`Пропущено строк:   ${числом(разбор.пропущено.length)}`);

  if (разбор.пропущено.length > 0) {
    п();
    п('Пропущенные строки (первые 10):');
    for (const строка of разбор.пропущено.slice(0, 10)) {
      п(`  строка ${строка.строка}: ${строка.причина} — ${JSON.stringify(строка.значения)}`);
    }
  }

  напечататьПримеры(п, разбор.позиции);
  напечататьСтатистику(п, разбор.позиции);
  напечататьПредупреждения(п, разбор);

  п();
  console.log(строки.join('\n'));
}

function напечататьПримеры(п: (т?: string) => void, позиции: Позиция[]): void {
  if (позиции.length === 0) return;

  п();
  п('Примеры позиций (первая, из середины, последняя):');
  const образцы = [позиции[0]!, позиции[Math.floor(позиции.length / 2)]!, позиции.at(-1)!];
  for (const позиция of образцы) п(`  ${описание(позиция)}`);
}

function описание(п: Позиция): string {
  const части = [
    `стр.${п.строка}`,
    п.штрихкод !== null ? `шк ${п.штрихкод}` : null,
    `арт. ${п.артикул ?? '—'}`,
    `«${п.наименование}»`,
    п.единица ?? '—',
    п.производитель ?? '—',
    `${п.цена} руб.`,
    `остаток: общий ${п.остатокОбщий}, Микрор-н ${п.остатокМикрорайон}, Березовская ${п.остатокБерезовская}`,
    п.категория !== null ? `категория: ${п.категория}` : null,
    п.видТовара !== null ? `вид: ${п.видТовара}` : null,
  ];
  return части.filter((часть) => часть !== null).join(' | ');
}

function напечататьСтатистику(п: (т?: string) => void, позиции: Позиция[]): void {
  if (позиции.length === 0) return;

  const цены = позиции.map((п) => п.цена).sort((а, б) => а - б);
  const сумма = (взять: (п: Позиция) => number) => позиции.reduce((и, п) => и + взять(п), 0);

  // Считаем расхождение общего остатка с суммой отделов, но НЕ исправляем его:
  // в базу и покупателю уходят числа ровно те, что записала Фора.
  const расхождений = позиции.filter(
    (п) => п.остатокОбщий !== п.остатокМикрорайон + п.остатокБерезовская,
  ).length;

  п();
  п('Статистика:');
  п(`  Цена:                    мин ${цены[0]}, медиана ${цены[Math.floor(цены.length / 2)]}, макс ${цены.at(-1)} руб.`);
  п(`  Позиций с ценой 0:       ${числом(позиции.filter((п) => п.цена === 0).length)}`);
  п(`  Сумма остатков:          общий ${числом(сумма((п) => п.остатокОбщий))}, Микрор-н ${числом(сумма((п) => п.остатокМикрорайон))}, Березовская ${числом(сумма((п) => п.остатокБерезовская))}`);
  п(`  Нет в наличии (общий 0): ${числом(позиции.filter((п) => п.остатокОбщий === 0).length)}`);
  п(`  Со штрихкодом:           ${числом(позиции.filter((п) => п.штрихкод !== null).length)}`);
  п(`  Общий != сумма отделов:  ${числом(расхождений)} — берём как в файле, сами не пересчитываем`);
}

function напечататьПредупреждения(п: (т?: string) => void, разбор: РазборПрайса): void {
  if (разбор.позиции.length >= ПОДОЗРИТЕЛЬНО_МАЛО_СТРОК) return;

  п();
  п('! ВНИМАНИЕ: похоже на неполную выгрузку.');
  п(`  Позиций всего ${числом(разбор.позиции.length)}, в боевом прайсе их около 11 900.`);
  п('  Так выглядит «пустышка» с FTP (~50 КБ): файл структурно исправен и товары в нём');
  п('  настоящие, поэтому парсер честно его разобрал. Опасна она именно этим — загрузи');
  п('  такую бот, и он правдиво скажет «нет в наличии» про тысячи товаров.');
  п('  Отбивать такие импорты будет валидатор на этапе 2 (порог строк + сравнение с прошлым).');
}

function числом(значение: number): string {
  return значение.toLocaleString('ru-RU');
}

главная().catch((причина: unknown) => {
  if (причина instanceof ОшибкаПрайса) {
    logger.error(`Не удалось разобрать прайс: ${причина.message}`);
    if (причина.подсказка !== undefined) logger.error(`Подсказка: ${причина.подсказка}`);
  } else {
    logger.error(`Непредвиденная ошибка: ${причина instanceof Error ? причина.stack : String(причина)}`);
  }
  process.exit(1);
});
