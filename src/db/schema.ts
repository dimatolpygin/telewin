/**
 * Схема БД (Drizzle).
 *
 * Устройство: каждый импорт — это **снимок целиком**. Позиции и остатки привязаны
 * к своему `import_id` и не трогаются после загрузки. Поверх снимков лежит указатель
 * «текущий» (`shop_state`), и он ведётся **по каждому магазину отдельно**.
 *
 * Почему так:
 * - Переключение «текущего» — это одна запись в `shop_state`, то есть атомарное
 *   действие. Пока импорт не проверен, покупатель продолжает видеть прошлый
 *   хороший снимок; частичных данных в «текущем» не бывает в принципе.
 * - Указатель на магазин, а не глобальный, потому что на этапе 8 точки могут
 *   приехать разными файлами с разной свежестью. Сейчас оба магазина в одном
 *   файле и указывают на один импорт, но переделывать схему не придётся.
 * - Снимок дороже по месту, чем нормализация по артикулу, но артикул в боевом
 *   файле бывает пустым и между базами может разъехаться (см. docs/PROJECT.md),
 *   так что ключа для нормализации у нас попросту нет.
 *
 * Деньги и остатки — `numeric`, не `double precision`: цена не должна плавать,
 * а остаток бывает дробным (метры, килограммы).
 */
import { sql } from 'drizzle-orm';
import {
  index,
  integer,
  numeric,
  pgTable,
  serial,
  text,
  timestamp,
  uniqueIndex,
} from 'drizzle-orm/pg-core';

/** Служебный словарь «ключ-значение» для отметок приложения. */
export const appMeta = pgTable('app_meta', {
  key: text('key').primaryKey(),
  value: text('value').notNull(),
  updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
});

/**
 * Магазины. `код` — внутренний ключ, на него завязан разбор колонок прайса.
 * `название` — то, как бот произносит их покупателю; клиент точные названия ещё
 * не прислал (открытый вопрос в STATUS.md), пока стоят рабочие.
 */
export const shops = pgTable('shops', {
  id: serial('id').primaryKey(),
  код: text('код').notNull().unique(),
  название: text('название').notNull(),
});

/**
 * Импорты — по строке на каждый обработанный файл, включая отбитые.
 * Отбитые тоже храним: это журнал того, что приезжало с FTP, и защита от
 * повторной обработки того же файла.
 */
export const imports = pgTable(
  'imports',
  {
    id: serial('id').primaryKey(),
    файл: text('файл').notNull(),
    /** sha256 содержимого. Уникален: один и тот же файл не обрабатываем дважды. */
    хеш: text('хеш').notNull(),
    размерБайт: integer('размер_байт').notNull(),
    раскладка: text('раскладка').notNull(),
    /** `ok` — принят и стал текущим; `отбит` — не прошёл валидацию. */
    статус: text('статус').notNull(),
    причинаОтказа: text('причина_отказа'),
    позиций: integer('позиций').notNull(),
    /** Время файла (mtime) — по нему считается свежесть данных, а не по времени загрузки. */
    файлОт: timestamp('файл_от', { withTimezone: true }),
    создан: timestamp('создан', { withTimezone: true }).notNull().defaultNow(),
  },
  (таблица) => [uniqueIndex('imports_хеш_uq').on(таблица.хеш)],
);

/** Позиции снимка. Живут внутри своего импорта и после загрузки не меняются. */
export const items = pgTable(
  'items',
  {
    id: serial('id').primaryKey(),
    importId: integer('import_id')
      .notNull()
      .references(() => imports.id, { onDelete: 'cascade' }),
    /** Номер строки в исходном файле — чтобы человек нашёл позицию глазами в Excel. */
    строка: integer('строка').notNull(),
    штрихкод: text('штрихкод'),
    артикул: text('артикул'),
    наименование: text('наименование').notNull(),
    /**
     * Наименование, приведённое к канону для поиска: буква/цифра разбиты пробелом
     * («м5» → «м 5»), lower, латинские гомоглифы сведены в кириллицу (m→м, c→с…).
     * Считается один раз при вставке (GENERATED STORED) функцией `norm_search`, и
     * та же функция нормализует запрос покупателя — так строка в базе и запрос
     * гарантированно живут в одном алфавите. Без этого «болт м5» (кириллица, слитно)
     * не совпал бы с «Болт M 5*12» (латинская M, раздельно) ни по FTS, ни по триграммам.
     * Свод именно в кириллицу, а не наоборот: русские слова остаются кириллицей и
     * стеммятся конфигурацией `russian` («саморезы» → «саморез»).
     */
    наименованиеNorm: text('наименование_norm').generatedAlwaysAs(
      sql`norm_search("наименование")`,
    ),
    единица: text('единица'),
    производитель: text('производитель'),
    цена: numeric('цена', { precision: 12, scale: 2 }).notNull(),
    /**
     * Общий остаток — ровно как в файле. НЕ сумма отделов: в данных Форы они
     * расходятся массово (572 позиции из 11 888), и подставлять своё число
     * вместо учётного нельзя.
     */
    остатокОбщий: numeric('остаток_общий', { precision: 14, scale: 3 }).notNull(),
    категория: text('категория'),
    видТовара: text('вид_товара'),
  },
  (таблица) => [
    index('items_import_id_idx').on(таблица.importId),
    // Точное совпадение по артикулу/штрихкоду — самый доверенный путь поиска.
    index('items_артикул_idx').on(таблица.артикул),
    index('items_штрихкод_idx').on(таблица.штрихкод),
    // Полнотекст (Postgres FTS, конфигурация russian) по нормализованному имени.
    index('items_наим_fts_idx').using('gin', sql`to_tsvector('russian', "наименование_norm")`),
    // Триграммы (pg_trgm) — устойчивость к опечаткам, ускоряет оператор `<%`.
    index('items_наим_trgm_idx').using('gin', sql`"наименование_norm" gin_trgm_ops`),
  ],
);

/**
 * Остатки в длинном формате: строка на пару (магазин, товар). Файл с двумя
 * колонками магазинов даёт две строки. Так раскладка файла перестаёт волновать
 * бота и схема заранее готова к двум файлам с разных точек (этап 8).
 */
export const stock = pgTable(
  'stock',
  {
    id: serial('id').primaryKey(),
    importId: integer('import_id')
      .notNull()
      .references(() => imports.id, { onDelete: 'cascade' }),
    itemId: integer('item_id')
      .notNull()
      .references(() => items.id, { onDelete: 'cascade' }),
    shopId: integer('shop_id')
      .notNull()
      .references(() => shops.id),
    остаток: numeric('остаток', { precision: 14, scale: 3 }).notNull(),
  },
  (таблица) => [
    uniqueIndex('stock_item_shop_uq').on(таблица.itemId, таблица.shopId),
    index('stock_import_shop_idx').on(таблица.importId, таблица.shopId),
  ],
);

/**
 * Указатель «текущий» — по строке на магазин. Единственное место, которое
 * переключается при удачном импорте, и единственное, куда смотрит бот.
 */
export const shopState = pgTable('shop_state', {
  shopId: integer('shop_id')
    .primaryKey()
    .references(() => shops.id),
  текущийImportId: integer('текущий_import_id')
    .notNull()
    .references(() => imports.id),
  /** Свежесть данных этого магазина: время файла, из которого они взяты. */
  данныеОт: timestamp('данные_от', { withTimezone: true }),
  обновлён: timestamp('обновлён', { withTimezone: true }).notNull().defaultNow(),
});
