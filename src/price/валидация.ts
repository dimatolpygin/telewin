/**
 * Валидация прайса ДО загрузки в базу.
 *
 * Это и есть «сердце не врать». Проверять надо именно здесь, потому что дальше
 * защиты нет: на этапе 1 замерено, что неполная выгрузка Форы («пустышка» 50 КБ)
 * — валидный .xls с правильной раскладкой и настоящими товарами. Она парсится
 * без единой ошибки. Ни чтение файла, ни определение раскладки её не поймают.
 *
 * Ловит её только арифметика: 122 позиции против 11 888 — это 1% от нормы.
 */
import type { РазборПрайса } from './парсер.js';

/**
 * Абсолютный минимум позиций. Ниже — точно неполная выгрузка: в боевом прайсе
 * ~11 900 позиций, в пустышке 122. Порог нарочно взят с большим запасом вниз:
 * он страхует случай, когда сравнить не с чем (первый импорт на чистой базе).
 */
export const МИНИМУМ_ПОЗИЦИЙ = 1000;

/**
 * Насколько прайс может «похудеть» относительно прошлого удачного импорта.
 * 0.5 = потеря больше половины позиций считается аварией, а не распродажей.
 */
export const ДОПУСТИМАЯ_ДОЛЯ_ОТ_ПРОШЛОГО = 0.5;

export interface ПрошлыйИмпорт {
  id: number;
  файл: string;
  позиций: number;
}

export type РезультатПроверки = { годен: true } | { годен: false; причина: string };

/**
 * Проверить разбор перед загрузкой.
 *
 * Порядок проверок — от абсолютных к относительным: сначала «это вообще похоже
 * на прайс», потом «это похоже на прошлый прайс».
 */
export function проверитьПрайс(
  разбор: РазборПрайса,
  прошлый: ПрошлыйИмпорт | null,
): РезультатПроверки {
  const позиций = разбор.позиции.length;

  if (позиций === 0) {
    return { годен: false, причина: 'в файле нет ни одной позиции' };
  }

  if (позиций < МИНИМУМ_ПОЗИЦИЙ) {
    return {
      годен: false,
      причина:
        `позиций всего ${позиций}, минимум ${МИНИМУМ_ПОЗИЦИЙ} — похоже на неполную выгрузку ` +
        `(в боевом прайсе около 11 900, в «пустышке» с FTP — 122)`,
    };
  }

  if (прошлый !== null) {
    const порог = Math.floor(прошлый.позиций * ДОПУСТИМАЯ_ДОЛЯ_ОТ_ПРОШЛОГО);
    if (позиций < порог) {
      const процент = ((позиций / прошлый.позиций) * 100).toFixed(1);
      return {
        годен: false,
        причина:
          `позиций ${позиций}, а в прошлом удачном импорте (#${прошлый.id}, ${прошлый.файл}) ` +
          `было ${прошлый.позиций} — это ${процент}%, потеряно больше половины`,
      };
    }
  }

  return { годен: true };
}
