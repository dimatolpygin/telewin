/**
 * Забор прайса из источника: один проход.
 *
 * Шаги: список → выбрать самый свежий → уже обрабатывали? → дождаться докачки →
 * скачать во временный файл → отдать импортёру этапа 2 → запомнить, что видели →
 * почистить старое.
 *
 * Фора кладёт файлы с временем в имени и копит их в папке; бот работает с самым
 * свежим (так и договаривались с клиентом). Поэтому берём один последний файл,
 * а не всё подряд. Защита от повторной ЗАГРУЗКИ — хеш содержимого в импортёре;
 * защита от повторного СКАЧИВАНИЯ — отметка последнего виденного имени, чтобы не
 * гонять 2.4 МБ на каждом опросе.
 */
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { eq } from 'drizzle-orm';
import { db } from '../db/index.js';
import { appMeta } from '../db/schema.js';
import { logger } from '../logger.js';
import { импортироватьПрайс, type ИтогИмпорта } from './импорт.js';
import {
  настройкиЗабора,
  создатьИсточник,
  type ИсточникПрайса,
  type ФайлИсточника,
} from './источник.js';
import { времяИзИмени } from './свежесть.js';

/** Ключ в app_meta, под которым лежит имя последнего скачанного файла источника. */
const КЛЮЧ_ПОСЛЕДНИЙ = 'источник:последний_файл';

const РАСШИРЕНИЯ = ['.xls', '.xlsx'];

export type ИтогЗабора =
  | { исход: 'нет_файлов' }
  | { исход: 'нет_нового'; имя: string }
  | { исход: 'заливается'; имя: string }
  | { исход: 'обработан'; имя: string; итог: ИтогИмпорта };

/** Один проход забора. Источник берётся из `.env`. */
export async function заборПрайса(): Promise<ИтогЗабора> {
  const источник = создатьИсточник();
  logger.info(`Источник прайса: ${источник.вид} · ${источник.адрес}`);

  try {
    return await пройти(источник);
  } finally {
    await источник.закрыть();
  }
}

async function пройти(источник: ИсточникПрайса): Promise<ИтогЗабора> {
  const настройки = настройкиЗабора();

  const файлы = (await источник.список()).filter((ф) =>
    РАСШИРЕНИЯ.some((р) => ф.имя.toLowerCase().endsWith(р)),
  );

  if (файлы.length === 0) {
    logger.info('В источнике нет файлов прайса (.xls/.xlsx).');
    return { исход: 'нет_файлов' };
  }

  const свежий = самыйСвежий(файлы);
  logger.info(
    `Найдено файлов: ${файлы.length}. Самый свежий: ${свежий.имя} ` +
      `(${(свежий.размер / 1024 / 1024).toFixed(2)} МБ, изменён ${свежий.изменён?.toISOString() ?? 'неизвестно'}).`,
  );

  const последний = await прочитатьПоследний();
  if (последний === свежий.имя) {
    logger.info(`Файл ${свежий.имя} уже обрабатывали — не скачиваю.`);
    return { исход: 'нет_нового', имя: свежий.имя };
  }

  // Дебаунс: файл на 2.4 МБ льётся минутами. Меряем размер дважды с паузой;
  // если между замерами он изменился — файл ещё заливается, ждём следующего прохода.
  if (!(await докачан(источник, свежий, настройки.ожиданиеСтабильностиМс))) {
    logger.warn(`Файл ${свежий.имя} ещё заливается (размер меняется) — пропускаю до следующего раза.`);
    return { исход: 'заливается', имя: свежий.имя };
  }

  const времянка = await mkdtemp(join(tmpdir(), 'telewin-прайс-'));
  const локальныйПуть = join(времянка, свежий.имя);

  try {
    logger.info(`Скачиваю ${свежий.имя}…`);
    await источник.скачать(свежий.имя, локальныйПуть);
    logger.info(`Скачан ${свежий.имя}. Передаю импортёру.`);

    // Свежесть — из имени файла (местное время клиента), запасной вариант —
    // mtime источника (UTC). Локальный mtime временного файла не годится: это
    // время скачивания.
    const файлОт = времяИзИмени(свежий.имя) ?? свежий.изменён ?? undefined;

    const итог = await импортироватьПрайс(локальныйПуть, {
      файлОт,
      исходноеИмя: свежий.имя,
    });

    // Запоминаем, что этот файл видели, при ЛЮБОМ исходе (в т.ч. «отбит»):
    // иначе одну и ту же пустышку будем качать на каждом опросе.
    await запомнитьПоследний(свежий.имя);

    if (настройки.хранитьФайлов > 0) {
      await почистить(источник, файлы, настройки.хранитьФайлов);
    }

    return { исход: 'обработан', имя: свежий.имя, итог };
  } finally {
    await rm(времянка, { recursive: true, force: true });
  }
}

/** Самый свежий файл: по времени изменения, затем по имени (оно ISO-сортируемо). */
function самыйСвежий(файлы: ФайлИсточника[]): ФайлИсточника {
  return [...файлы].sort((а, б) => {
    const разница = ключВремени(б) - ключВремени(а);
    return разница !== 0 ? разница : б.имя.localeCompare(а.имя);
  })[0]!;
}

function ключВремени(ф: ФайлИсточника): number {
  return ф.изменён?.getTime() ?? времяИзИмени(ф.имя)?.getTime() ?? 0;
}

/** Докачан ли файл: размер не меняется между двумя замерами. */
async function докачан(
  источник: ИсточникПрайса,
  файл: ФайлИсточника,
  ожиданиеМс: number,
): Promise<boolean> {
  if (ожиданиеМс <= 0) return true;
  await пауза(ожиданиеМс);
  const повторно = (await источник.список()).find((ф) => ф.имя === файл.имя);
  return повторно !== undefined && повторно.размер === файл.размер;
}

/** Оставить только `хранить` самых свежих файлов, остальные удалить из источника. */
async function почистить(
  источник: ИсточникПрайса,
  файлы: ФайлИсточника[],
  хранить: number,
): Promise<void> {
  const поУбыванию = [...файлы].sort((а, б) => ключВремени(б) - ключВремени(а));
  const наУдаление = поУбыванию.slice(хранить);
  for (const файл of наУдаление) {
    try {
      await источник.удалить(файл.имя);
      logger.info(`Удалён старый файл из источника: ${файл.имя}`);
    } catch (причина) {
      logger.warn(`Не удалось удалить ${файл.имя}: ${причина instanceof Error ? причина.message : String(причина)}`);
    }
  }
}

async function прочитатьПоследний(): Promise<string | null> {
  const [строка] = await db
    .select({ value: appMeta.value })
    .from(appMeta)
    .where(eq(appMeta.key, КЛЮЧ_ПОСЛЕДНИЙ))
    .limit(1);
  return строка?.value ?? null;
}

async function запомнитьПоследний(имя: string): Promise<void> {
  await db
    .insert(appMeta)
    .values({ key: КЛЮЧ_ПОСЛЕДНИЙ, value: имя })
    .onConflictDoUpdate({ target: appMeta.key, set: { value: имя, updatedAt: new Date() } });
}

function пауза(мс: number): Promise<void> {
  return new Promise((готово) => setTimeout(готово, мс));
}
