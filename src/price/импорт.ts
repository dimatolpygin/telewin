/**
 * Загрузка прайса в базу.
 *
 * Порядок жёсткий и менять его нельзя:
 *   1. хеш файла → уже обрабатывали? выходим, не создавая импорт;
 *   2. разбор файла в память;
 *   3. **валидация ДО записи** — мусор до базы не доезжает вовсе;
 *   4. одна транзакция: импорт + позиции + остатки + переключение указателя.
 *
 * Указатель «текущий» переключается последним действием внутри транзакции.
 * Поэтому оборванный импорт (Ctrl+C, падение, обрыв сети) откатывается целиком:
 * частичных данных в «текущем» не бывает, покупатель всё это время видит
 * прошлый хороший снимок.
 */
import { createHash } from 'node:crypto';
import { readFile, stat } from 'node:fs/promises';
import { basename } from 'node:path';
import { and, desc, eq, ilike } from 'drizzle-orm';
import { db } from '../db/index.js';
import { imports, items, shopState, shops, stock } from '../db/schema.js';
import { logger } from '../logger.js';
import { МАГАЗИНЫ } from './магазины.js';
import { разобратьПрайс, type Позиция } from './парсер.js';
import { времяИзИмени } from './свежесть.js';
import { проверитьПрайс, type ПрошлыйИмпорт } from './валидация.js';

/**
 * Postgres не принимает больше 65535 параметров в одном запросе, а у нас 11 888
 * позиций по 11 полей. Режем на куски с запасом.
 */
const ПОЗИЦИЙ_ЗА_РАЗ = 2000;
const ОСТАТКОВ_ЗА_РАЗ = 5000;

export type ИтогИмпорта =
  | { исход: 'загружен'; importId: number; позиций: number; остатков: number }
  | { исход: 'дубль'; importId: number; статус: string; файл: string }
  | { исход: 'отбит'; importId: number; причина: string };

export interface ОпцииИмпорта {
  /**
   * Момент выгрузки прайса из Форы. Задаёт забор с FTP (из имени файла или mtime
   * источника). Если не задан — пробуем достать из имени файла, иначе локальный
   * mtime. Локальный mtime — худший вариант: для скачанного файла это время
   * скачивания, а бот показывает эту дату покупателю.
   */
  файлОт?: Date;
  /** Имя для журнала. Для FTP — исходное имя на сервере, а не путь во времянке. */
  исходноеИмя?: string;
}

export async function импортироватьПрайс(
  путь: string,
  опции: ОпцииИмпорта = {},
): Promise<ИтогИмпорта> {
  const данные = await readFile(путь);
  const хеш = createHash('sha256').update(данные).digest('hex');
  const имяДляЖурнала = опции.исходноеИмя ?? путь;

  // Дедуп до всякой работы: файл мог приехать с FTP повторно.
  // Сверяем и с отбитыми тоже — иначе автозабор (этап 3) будет перемалывать
  // одну и ту же пустышку на каждом круге и засорять журнал.
  const [прежний] = await db
    .select({ id: imports.id, статус: imports.статус, файл: imports.файл })
    .from(imports)
    .where(eq(imports.хеш, хеш))
    .limit(1);

  if (прежний !== undefined) {
    return { исход: 'дубль', importId: прежний.id, статус: прежний.статус, файл: прежний.файл };
  }

  const разбор = await разобратьПрайс(путь);
  // Время выгрузки: явно переданное → из имени файла → локальный mtime (худший).
  const файлОт =
    опции.файлОт ?? времяИзИмени(basename(имяДляЖурнала)) ?? (await stat(путь)).mtime;

  const [прошлый] = await db
    .select({ id: imports.id, файл: imports.файл, позиций: imports.позиций })
    .from(imports)
    .where(eq(imports.статус, 'ok'))
    .orderBy(desc(imports.id))
    .limit(1);

  const проверка = проверитьПрайс(разбор, (прошлый as ПрошлыйИмпорт | undefined) ?? null);

  if (!проверка.годен) {
    // Отбитый импорт фиксируем строкой в журнале — но БЕЗ позиций и остатков,
    // и указателя «текущий» не касаемся.
    const [запись] = await db
      .insert(imports)
      .values({
        файл: имяДляЖурнала,
        хеш,
        размерБайт: разбор.размерБайт,
        раскладка: разбор.раскладка.имя,
        статус: 'отбит',
        причинаОтказа: проверка.причина,
        позиций: разбор.позиции.length,
        файлОт,
      })
      .returning({ id: imports.id });

    return { исход: 'отбит', importId: запись!.id, причина: проверка.причина };
  }

  return await db.transaction(async (тр) => {
    const [запись] = await тр
      .insert(imports)
      .values({
        файл: имяДляЖурнала,
        хеш,
        размерБайт: разбор.размерБайт,
        раскладка: разбор.раскладка.имя,
        статус: 'ok',
        позиций: разбор.позиции.length,
        файлОт,
      })
      .returning({ id: imports.id });

    const importId = запись!.id;
    const магазины = await обеспечитьМагазины(тр);

    const остатков = await залить(тр, importId, разбор.позиции, магазины);

    // Последним действием — переключаем указатель. До этой строки бот отвечает
    // по прошлому снимку, после — по новому. Промежуточного состояния нет.
    for (const магазин of магазины) {
      await тр
        .insert(shopState)
        .values({ shopId: магазин.id, текущийImportId: importId, данныеОт: файлОт })
        .onConflictDoUpdate({
          target: shopState.shopId,
          set: { текущийImportId: importId, данныеОт: файлОт, обновлён: new Date() },
        });
    }

    return { исход: 'загружен', importId, позиций: разбор.позиции.length, остатков };
  });
}

type Транзакция = Parameters<Parameters<typeof db.transaction>[0]>[0];

interface МагазинВБазе {
  id: number;
  код: string;
  роль: (typeof МАГАЗИНЫ)[number]['роль'];
}

/** Магазины заводятся сами при первом импорте: отдельный шаг настройки только мешал бы. */
async function обеспечитьМагазины(тр: Транзакция): Promise<МагазинВБазе[]> {
  const итог: МагазинВБазе[] = [];

  for (const магазин of МАГАЗИНЫ) {
    const [запись] = await тр
      .insert(shops)
      .values({ код: магазин.код, название: магазин.название })
      .onConflictDoNothing({ target: shops.код })
      .returning({ id: shops.id });

    const id =
      запись?.id ??
      (
        await тр.select({ id: shops.id }).from(shops).where(eq(shops.код, магазин.код)).limit(1)
      )[0]!.id;

    итог.push({ id, код: магазин.код, роль: магазин.роль });
  }

  return итог;
}

/** Залить позиции и остатки кусками. Возвращает число строк в stock. */
async function залить(
  тр: Транзакция,
  importId: number,
  позиции: Позиция[],
  магазины: МагазинВБазе[],
): Promise<number> {
  let остатков = 0;
  let строкиОстатков: (typeof stock.$inferInsert)[] = [];

  for (let начало = 0; начало < позиции.length; начало += ПОЗИЦИЙ_ЗА_РАЗ) {
    const кусок = позиции.slice(начало, начало + ПОЗИЦИЙ_ЗА_РАЗ);

    const вставленные = await тр
      .insert(items)
      .values(
        кусок.map((поз) => ({
          importId,
          строка: поз.строка,
          штрихкод: поз.штрихкод,
          артикул: поз.артикул,
          наименование: поз.наименование,
          единица: поз.единица,
          производитель: поз.производитель,
          цена: поз.цена.toFixed(2),
          остатокОбщий: поз.остатокОбщий.toFixed(3),
          категория: поз.категория,
          видТовара: поз.видТовара,
        })),
      )
      .returning({ id: items.id });

    // Порядок returning совпадает с порядком values — на нём и держится связка
    // позиции с её остатками.
    кусок.forEach((поз, i) => {
      for (const магазин of магазины) {
        строкиОстатков.push({
          importId,
          itemId: вставленные[i]!.id,
          shopId: магазин.id,
          остаток: остатокПоРоли(поз, магазин.роль).toFixed(3),
        });
      }
    });

    while (строкиОстатков.length >= ОСТАТКОВ_ЗА_РАЗ) {
      const порция = строкиОстатков.slice(0, ОСТАТКОВ_ЗА_РАЗ);
      строкиОстатков = строкиОстатков.slice(ОСТАТКОВ_ЗА_РАЗ);
      await тр.insert(stock).values(порция);
      остатков += порция.length;
    }

    logger.debug(`Загружено позиций: ${Math.min(начало + ПОЗИЦИЙ_ЗА_РАЗ, позиции.length)} из ${позиции.length}`);
  }

  if (строкиОстатков.length > 0) {
    await тр.insert(stock).values(строкиОстатков);
    остатков += строкиОстатков.length;
  }

  return остатков;
}

function остатокПоРоли(позиция: Позиция, роль: МагазинВБазе['роль']): number {
  return роль === 'остатокМикрорайон' ? позиция.остатокМикрорайон : позиция.остатокБерезовская;
}

/** Список импортов для CLI: что приезжало и чем закончилось. */
export async function списокИмпортов(сколько = 20) {
  return await db
    .select({
      id: imports.id,
      файл: imports.файл,
      статус: imports.статус,
      позиций: imports.позиций,
      раскладка: imports.раскладка,
      размерБайт: imports.размерБайт,
      причинаОтказа: imports.причинаОтказа,
      файлОт: imports.файлОт,
      создан: imports.создан,
    })
    .from(imports)
    .orderBy(desc(imports.id))
    .limit(сколько);
}

/** Свежесть по каждому магазину: на какой импорт он смотрит и от какого числа данные. */
export async function свежестьМагазинов() {
  return await db
    .select({
      код: shops.код,
      название: shops.название,
      importId: shopState.текущийImportId,
      данныеОт: shopState.данныеОт,
      обновлён: shopState.обновлён,
      файл: imports.файл,
    })
    .from(shops)
    .leftJoin(shopState, eq(shopState.shopId, shops.id))
    .leftJoin(imports, eq(imports.id, shopState.текущийImportId))
    .orderBy(shops.id);
}

export interface НайденнаяПозиция {
  наименование: string;
  артикул: string | null;
  единица: string | null;
  цена: string;
  остатокОбщий: string;
  остаток: string;
  магазин: string;
  данныеОт: Date | null;
  importId: number;
}

/**
 * Минимальный поиск по текущему снимку — подстрокой, для проверки этапа 2.
 * Настоящий поиск (нормализация запроса, ранжирование) — этап 4.
 *
 * Запрос идёт от `shop_state`, а не от «последнего импорта»: бот обязан видеть
 * ровно то, на что указывает магазин, иначе отбитый импорт мог бы просочиться.
 */
export async function найтиВТекущем(запрос: string, предел = 20): Promise<НайденнаяПозиция[]> {
  const итог: НайденнаяПозиция[] = [];
  const состояния = await свежестьМагазинов();

  for (const состояние of состояния) {
    if (состояние.importId === null) continue;

    const строки = await db
      .select({
        наименование: items.наименование,
        артикул: items.артикул,
        единица: items.единица,
        цена: items.цена,
        остатокОбщий: items.остатокОбщий,
        остаток: stock.остаток,
      })
      .from(items)
      .innerJoin(stock, eq(stock.itemId, items.id))
      .innerJoin(shops, eq(shops.id, stock.shopId))
      .where(
        and(
          eq(items.importId, состояние.importId),
          eq(shops.код, состояние.код),
          ilike(items.наименование, `%${экранироватьLike(запрос.trim())}%`),
        ),
      )
      .orderBy(items.строка)
      .limit(предел);

    for (const строка of строки) {
      итог.push({
        ...строка,
        магазин: состояние.название,
        данныеОт: состояние.данныеОт,
        importId: состояние.importId,
      });
    }
  }

  return итог;
}

/**
 * Экранируем спецсимволы LIKE. Значение уходит параметром, так что инъекции тут
 * нет, но без экранирования «%» в запросе покупателя молча совпал бы со всем
 * подряд, а «_» — с любым символом.
 */
function экранироватьLike(текст: string): string {
  return текст.replace(/[\\%_]/g, (символ) => `\\${символ}`);
}
