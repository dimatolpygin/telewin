/**
 * Ошибка разбора прайса.
 *
 * Текст сообщения пишется сразу для человека (оператора или разработчика) и
 * показывается как есть: библиотечные ошибки вроде
 * «Cannot set properties of undefined (setting 'name')» не объясняют ничего.
 */
export class ОшибкаПрайса extends Error {
  /** Что делать дальше — печатается отдельной строкой под сообщением. */
  readonly подсказка: string | undefined;

  constructor(сообщение: string, подсказка?: string) {
    super(сообщение);
    this.name = 'ОшибкаПрайса';
    this.подсказка = подсказка;
  }
}
