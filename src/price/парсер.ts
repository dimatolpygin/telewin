/**
 * Чтение прайса «Мемо Фора» из .xls (BIFF, cp1251) и .xlsx.
 *
 * Парсер отвечает ровно на один вопрос: «что лежит в этом файле». Он не решает,
 * годятся ли данные для загрузки в базу, — это валидация импорта (этап 2).
 * Разделение принципиальное: неполная выгрузка Форы («пустышка» ~50 КБ) —
 * структурно безупречный файл с настоящими товарами, просто их 122 вместо 11 888.
 * Парсеру ломать в ней нечего, и врать, что файл битый, он не станет.
 */
import { readFile } from 'node:fs/promises';
import * as XLSX from 'xlsx';
import { ОшибкаПрайса } from './ошибки.js';
import {
  какТекст,
  какЧисло,
  определитьРаскладку,
  type Раскладка,
  type Роль,
  type Ячейка,
} from './раскладка.js';

export interface Позиция {
  /** Номер строки в файле, с единицы: чтобы человек нашёл её глазами в Excel. */
  строка: number;
  штрихкод: string | null;
  артикул: string | null;
  наименование: string;
  единица: string | null;
  производитель: string | null;
  цена: number;
  /**
   * Остатки — как в файле. Общий НЕ считается как сумма отделов: в данных Форы
   * они расходятся (у «Болт M 5*12» общий 424 против 158+265=423), и придумывать
   * своё число вместо учётного нельзя.
   */
  остатокОбщий: number;
  остатокМикрорайон: number;
  остатокБерезовская: number;
  категория: string | null;
  видТовара: string | null;
}

export interface ПропущеннаяСтрока {
  строка: number;
  причина: string;
  значения: Ячейка[];
}

export interface РазборПрайса {
  файл: string;
  размерБайт: number;
  лист: string;
  раскладка: Раскладка;
  /** Доля строк выборки, лёгшая на раскладку: 1 = формат распознан железно. */
  доляСовпадения: number;
  /** Сколько непустых строк нашлось на листе. */
  строкСДанными: number;
  позиции: Позиция[];
  пропущено: ПропущеннаяСтрока[];
}

/** Разобрать файл прайса. Бросает ОшибкаПрайса с человеческим текстом. */
export async function разобратьПрайс(путь: string): Promise<РазборПрайса> {
  const данные = await прочитатьФайл(путь);

  if (данные.byteLength === 0) {
    throw new ОшибкаПрайса(
      `Файл пустой (0 байт): ${путь}`,
      'Скорее всего выгрузка оборвалась или файл не докачался с FTP.',
    );
  }

  const книга = прочитатьКнигу(данные, путь);

  const имяЛиста = книга.SheetNames[0];
  if (имяЛиста === undefined) {
    throw new ОшибкаПрайса(
      `В файле нет ни одного листа: ${путь}`,
      'Это не похоже на выгрузку Форы — проверьте, тот ли файл забрали с FTP.',
    );
  }

  const лист = книга.Sheets[имяЛиста];
  if (лист === undefined) {
    throw new ОшибкаПрайса(`Лист «${имяЛиста}» не читается: ${путь}`);
  }

  // header: 1 — заголовков в выгрузке нет, данные идут с первой строки.
  // raw: true — нужны исходные значения, а не то, как их показал бы Excel.
  const строки = XLSX.utils.sheet_to_json<Ячейка[]>(лист, {
    header: 1,
    raw: true,
    blankrows: false,
    defval: null,
  });

  if (строки.length === 0) {
    throw new ОшибкаПрайса(
      `Лист «${имяЛиста}» пуст — ни одной строки с данными: ${путь}`,
      'Фора выгрузила файл, но не положила в него данные.',
    );
  }

  const { раскладка, доля } = определитьРаскладку(строки);
  const индексы = индексыРолей(раскладка);

  const позиции: Позиция[] = [];
  const пропущено: ПропущеннаяСтрока[] = [];

  строки.forEach((строка, i) => {
    const номер = i + 1;
    const итог = собратьПозицию(строка, индексы, номер);
    if ('причина' in итог) {
      пропущено.push({ строка: номер, причина: итог.причина, значения: строка });
    } else {
      позиции.push(итог);
    }
  });

  return {
    файл: путь,
    размерБайт: данные.byteLength,
    лист: имяЛиста,
    раскладка,
    доляСовпадения: доля,
    строкСДанными: строки.length,
    позиции,
    пропущено,
  };
}

async function прочитатьФайл(путь: string): Promise<Buffer> {
  try {
    return await readFile(путь);
  } catch (причина) {
    const код = (причина as NodeJS.ErrnoException).code;
    if (код === 'ENOENT') throw new ОшибкаПрайса(`Файл не найден: ${путь}`);
    if (код === 'EISDIR') throw new ОшибкаПрайса(`Это папка, а не файл: ${путь}`);
    if (код === 'EACCES') throw new ОшибкаПрайса(`Нет доступа к файлу: ${путь}`);
    throw new ОшибкаПрайса(
      `Не удалось прочитать файл ${путь}: ${причина instanceof Error ? причина.message : String(причина)}`,
    );
  }
}

/**
 * SheetJS на обрезанном файле падает с «Cannot set properties of undefined
 * (setting 'name')» — по такой ошибке невозможно понять, что случилось.
 * Переводим на русский и говорим, куда смотреть.
 */
function прочитатьКнигу(данные: Buffer, путь: string): XLSX.WorkBook {
  try {
    // Кодировку (cp1251 у .xls от Форы) SheetJS берёт из самого файла.
    // Не задаём её жёстко: следующий файл может приехать в .xlsx с UTF-8.
    return XLSX.read(данные, { type: 'buffer', raw: true });
  } catch (причина) {
    throw new ОшибкаПрайса(
      `Не удалось прочитать ${путь} как книгу Excel: ${причина instanceof Error ? причина.message : String(причина)}`,
      `Размер файла ${(данные.byteLength / 1024).toFixed(0)} КБ. ` +
        'Обычно так выглядит недокачанный или обрезанный файл — сверьте размер с тем, что лежит на FTP.',
    );
  }
}

type Индексы = Partial<Record<Роль, number>>;

function индексыРолей(раскладка: Раскладка): Индексы {
  const индексы: Индексы = {};
  раскладка.колонки.forEach((роль, i) => {
    индексы[роль] = i;
  });
  return индексы;
}

function текстПоРоли(строка: Ячейка[], индексы: Индексы, роль: Роль): string | null {
  const i = индексы[роль];
  return i === undefined ? null : какТекст(строка[i]);
}

function числоПоРоли(строка: Ячейка[], индексы: Индексы, роль: Роль): number | null {
  const i = индексы[роль];
  return i === undefined ? null : какЧисло(строка[i]);
}

/**
 * Собрать позицию из строки. Строка без наименования, цены или остатков — это не
 * товар: молча подставлять ноль нельзя (ноль остатка значит «нет в наличии»,
 * и бот скажет это покупателю). Такую строку пропускаем и показываем в отчёте.
 */
function собратьПозицию(
  строка: Ячейка[],
  индексы: Индексы,
  номер: number,
): Позиция | { причина: string } {
  const наименование = текстПоРоли(строка, индексы, 'наименование');
  if (наименование === null) return { причина: 'пустое наименование' };

  const цена = числоПоРоли(строка, индексы, 'цена');
  if (цена === null) return { причина: 'цена не число' };

  const остатокОбщий = числоПоРоли(строка, индексы, 'остатокОбщий');
  const остатокМикрорайон = числоПоРоли(строка, индексы, 'остатокМикрорайон');
  const остатокБерезовская = числоПоРоли(строка, индексы, 'остатокБерезовская');

  if (остатокОбщий === null || остатокМикрорайон === null || остатокБерезовская === null) {
    return { причина: 'остаток не число' };
  }

  return {
    строка: номер,
    штрихкод: текстПоРоли(строка, индексы, 'штрихкод'),
    артикул: текстПоРоли(строка, индексы, 'артикул'),
    наименование,
    единица: текстПоРоли(строка, индексы, 'единица'),
    производитель: текстПоРоли(строка, индексы, 'производитель'),
    цена,
    остатокОбщий,
    остатокМикрорайон,
    остатокБерезовская,
    категория: текстПоРоли(строка, индексы, 'категория'),
    видТовара: текстПоРоли(строка, индексы, 'видТовара'),
  };
}
