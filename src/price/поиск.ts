/**
 * Детерминированный поиск по прайсу (этап 4). Никакого ИИ: числа берутся из БД
 * и обязаны сходиться с прямым SQL. Семантика («гвозди сотка» → «Гвоздь
 * строительный 100») — это этап 5, здесь её нет.
 *
 * Три канала совпадения, от самого доверенного к самому терпимому:
 *   1. точное совпадение по артикулу или штрихкоду — однозначный запрос;
 *   2. полнотекст (Postgres FTS, конфигурация `russian`) по нормализованному имени;
 *   3. триграммы (pg_trgm) — вытягивают опечатки, которые FTS уже не берёт.
 *
 * Запрос и наименования нормализуются ОДНОЙ функцией `norm_search` (см. миграцию
 * 0002): буква/цифра разбиваются пробелом, латинские гомоглифы сводятся в кириллицу.
 * Без этого «болт м5» (кириллица, слитно) не совпал бы с «Болт M 5*12» (латинская M,
 * раздельно) ни по FTS, ни по триграммам — проверено на боевых данных.
 *
 * Если есть точное совпадение по артикулу/штрихкоду — отдаём ТОЛЬКО его и не
 * подмешиваем нечёткие кандидаты: покупатель, назвавший артикул, хочет этот товар.
 *
 * Результат — по товару, а не по (товар × магазин): наименование и цена одни, а
 * остаток и свежесть — по каждой точке отдельно. Свежесть берётся из `shop_state`
 * этой точки, поэтому магазины с разной датой данных (этап 8) покажутся честно
 * раздельно.
 */
import { sql } from 'drizzle-orm';
import { db } from '../db/index.js';

/**
 * Порог триграммной близости (`word_similarity`). Опечатка «болd м5» против
 * «Болт M 5*12» даёт 0.636 — проходит с запасом; мусор «асдфгх» даёт 0 — отсекается.
 * 0.4 выбран замером на боевом прайсе, а не на глаз.
 */
const ПОРОГ_ТРИГРАММ = 0.4;

/** Сколько товаров максимум возвращаем по одному запросу. */
const ПРЕДЕЛ_ПО_УМОЛЧАНИЮ = 20;

/** Как именно нашёлся товар — для честности вывода и отладки. */
export type СпособСовпадения = 'артикул' | 'штрихкод' | 'название' | 'похоже';

export interface ОстатокТочки {
  код: string;
  магазин: string;
  остаток: string;
  /** Свежесть данных этой точки: момент выгрузки прайса, из которого взят остаток. */
  данныеОт: Date | null;
}

export interface РезультатПоиска {
  наименование: string;
  артикул: string | null;
  штрихкод: string | null;
  единица: string | null;
  цена: string;
  остатокОбщий: string;
  способ: СпособСовпадения;
  точки: ОстатокТочки[];
}

/** Одна строка сырого ответа БД: товар, размноженный по точкам. */
interface СтрокаОтвета {
  id: number;
  наименование: string;
  артикул: string | null;
  штрихкод: string | null;
  единица: string | null;
  цена: string;
  остаток_общий: string;
  способ: СпособСовпадения;
  shop_код: string;
  shop_название: string;
  остаток: string;
  данные_от: Date | null;
}

export async function искать(
  запрос: string,
  предел = ПРЕДЕЛ_ПО_УМОЛЧАНИЮ,
): Promise<РезультатПоиска[]> {
  const текст = запрос.trim();
  if (текст === '') return [];

  // Порог триграмм и отключение JIT — на одну транзакцию (SET LOCAL). JIT на этих
  // мелких запросах только добавлял ~0.1 с компиляции; без него укладываемся в единицы мс.
  const строки = await db.transaction(async (тр) => {
    await тр.execute(sql`set local pg_trgm.word_similarity_threshold = ${sql.raw(String(ПОРОГ_ТРИГРАММ))}`);
    await тр.execute(sql`set local jit = off`);

    const результат = await тр.execute(sql`
      with q as (
        select norm_search(${текст}) as qn,
               plainto_tsquery('russian', norm_search(${текст})) as tq
      ),
      cand as (
        select i.id, i.import_id, i.наименование, i.артикул, i.штрихкод,
               i.единица, i.цена, i.остаток_общий, i.строка,
               case when i.артикул = ${текст} then 3
                    when i.штрихкод = ${текст} then 3
                    when to_tsvector('russian', i.наименование_norm) @@ (select tq from q) then 2
                    else 1 end as tier,
               case when i.артикул = ${текст} then 'артикул'
                    when i.штрихкод = ${текст} then 'штрихкод'
                    when to_tsvector('russian', i.наименование_norm) @@ (select tq from q) then 'название'
                    else 'похоже' end as способ,
               word_similarity((select qn from q), i.наименование_norm) as ws
        from items i
        where i.import_id in (select distinct текущий_import_id from shop_state)
          and ( i.артикул = ${текст}
                or i.штрихкод = ${текст}
                or to_tsvector('russian', i.наименование_norm) @@ (select tq from q)
                or (select qn from q) <% i.наименование_norm )
      ),
      picked as (
        select * from cand
        where case when exists (select 1 from cand where tier = 3)
                   then tier = 3 else true end
        order by tier desc, ws desc, строка
        limit ${предел}
      )
      select p.id, p.наименование, p.артикул, p.штрихкод, p.единица, p.цена,
             p.остаток_общий, p.способ,
             s.код as shop_код, s.название as shop_название,
             st.остаток, ss.данные_от
      from picked p
      join stock st on st.item_id = p.id
      join shop_state ss on ss.текущий_import_id = p.import_id and ss.shop_id = st.shop_id
      join shops s on s.id = st.shop_id
      order by p.tier desc, p.ws desc, p.строка, s.id
    `);

    return результат as unknown as СтрокаОтвета[];
  });

  // Схлопываем (товар × точка) в один товар с массивом точек. Строки одного
  // товара идут подряд (порядок держит ORDER BY), но группируем через Map —
  // не полагаемся на соседство.
  const поId = new Map<number, РезультатПоиска>();
  for (const строка of строки) {
    let товар = поId.get(строка.id);
    if (товар === undefined) {
      товар = {
        наименование: строка.наименование,
        артикул: строка.артикул,
        штрихкод: строка.штрихкод,
        единица: строка.единица,
        цена: строка.цена,
        остатокОбщий: строка.остаток_общий,
        способ: строка.способ,
        точки: [],
      };
      поId.set(строка.id, товар);
    }
    товар.точки.push({
      код: строка.shop_код,
      магазин: строка.shop_название,
      остаток: строка.остаток,
      данныеОт: строка.данные_от,
    });
  }

  return [...поId.values()];
}
