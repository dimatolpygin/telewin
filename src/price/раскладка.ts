/**
 * Раскладка колонок прайса и её автоопределение.
 *
 * Формат выгрузки «Мемо Фора» настраивается клиентом и уже менялся: приходили
 * файлы на 11 и на 8 колонок. Поэтому порядок колонок нигде не зашит намертво —
 * раскладка подбирается по ширине строки и типам ячеек.
 *
 * Заголовков в файле нет, данные идут с первой строки, так что опереться на
 * названия колонок нельзя — только на сами значения.
 */
import { ОшибкаПрайса } from './ошибки.js';

/** Смысл колонки. Имена ролей — единственное, на что опирается остальной код. */
export type Роль =
  | 'штрихкод'
  | 'артикул'
  | 'наименование'
  | 'единица'
  | 'производитель'
  | 'цена'
  | 'остатокОбщий'
  | 'остатокМикрорайон'
  | 'остатокБерезовская'
  | 'категория'
  | 'видТовара';

export interface Раскладка {
  имя: string;
  /** Роль каждой колонки по позиции. Длина = ожидаемая ширина строки. */
  колонки: Роль[];
}

/** Значение ячейки в том виде, в каком его отдаёт SheetJS. */
export type Ячейка = string | number | boolean | null | undefined;

/**
 * Известные раскладки. Новый формат от клиента = новая запись здесь,
 * трогать парсер не нужно.
 */
export const РАСКЛАДКИ: readonly Раскладка[] = [
  {
    имя: '11 колонок (со штрихкодом, категорией и видом товара)',
    колонки: [
      'штрихкод',
      'артикул',
      'наименование',
      'единица',
      'производитель',
      'цена',
      'остатокОбщий',
      'остатокМикрорайон',
      'остатокБерезовская',
      'категория',
      'видТовара',
    ],
  },
  {
    имя: '8 колонок (боевая: без штрихкода, категории и вида товара)',
    колонки: [
      'артикул',
      'наименование',
      'единица',
      'производитель',
      'цена',
      'остатокОбщий',
      'остатокМикрорайон',
      'остатокБерезовская',
    ],
  },
];

/**
 * Число из ячейки. Фора пишет дробное с запятой («3,5») и иногда разделяет
 * тысячи пробелом или неразрывным пробелом.
 */
export function какЧисло(значение: Ячейка): number | null {
  if (typeof значение === 'number') return Number.isFinite(значение) ? значение : null;
  if (typeof значение !== 'string') return null;

  const очищено = значение.replace(/[\s ]/g, '').replace(',', '.');
  if (очищено === '') return null;

  const число = Number(очищено);
  return Number.isFinite(число) ? число : null;
}

/** Текст из ячейки. Пустая строка и пробелы — это «нет значения», а не «''». */
export function какТекст(значение: Ячейка): string | null {
  if (значение === null || значение === undefined) return null;
  const текст = String(значение).trim();
  return текст === '' ? null : текст;
}

/**
 * Что мы считаем допустимым значением для роли.
 *
 * Проверки нарочно широкие: они отсеивают чужой файл, а не бракуют товар.
 * Строгая проверка данных — задача этапа 2 (валидация импорта).
 */
const ПРОВЕРКИ: Record<Роль, (значение: Ячейка) => boolean> = {
  // Штрихкод бывает пустым; когда есть — это только цифры.
  штрихкод: (з) => {
    const текст = какТекст(з);
    return текст === null || /^\d{6,14}$/.test(текст);
  },
  // Артикул — внутренний код Форы, вид у него любой: «00008», «ДН-101-0030»,
  // «70331/37269/39682», и в боевых файлах он бывает пустым. Не проверяем.
  артикул: () => true,
  наименование: (з) => {
    const текст = какТекст(з);
    return текст !== null && текст.length >= 2 && какЧисло(з) === null;
  },
  единица: (з) => {
    const текст = какТекст(з);
    return текст !== null && текст.length <= 16 && какЧисло(з) === null;
  },
  производитель: (з) => какЧисло(з) === null,
  цена: (з) => {
    const число = какЧисло(з);
    return число !== null && число >= 0;
  },
  остатокОбщий: (з) => какЧисло(з) !== null,
  остатокМикрорайон: (з) => какЧисло(з) !== null,
  остатокБерезовская: (з) => какЧисло(з) !== null,
  категория: (з) => какЧисло(з) === null,
  видТовара: (з) => какЧисло(з) === null,
};

/** Доля строк выборки, которая должна лечь на раскладку целиком. */
const ПОРОГ_СОВПАДЕНИЯ = 0.9;

/** Сколько строк проверяем при определении. Больше не нужно — разброс уже виден. */
const РАЗМЕР_ВЫБОРКИ = 500;

export interface ВыборРаскладки {
  раскладка: Раскладка;
  /** Доля строк выборки, подошедших целиком: 1 = легло всё. */
  доля: number;
}

/** Равномерная выборка по всему файлу: брак может начаться и в середине. */
function выборка<T>(строки: readonly T[], сколько = РАЗМЕР_ВЫБОРКИ): T[] {
  if (строки.length <= сколько) return [...строки];
  const шаг = строки.length / сколько;
  const итог: T[] = [];
  for (let i = 0; i < сколько; i++) итог.push(строки[Math.floor(i * шаг)]!);
  return итог;
}

/** Самая частая ширина строки. Устойчивее, чем диапазон листа: лишняя ячейка сбоку не собьёт. */
function модальнаяШирина(строки: readonly Ячейка[][]): number {
  const счёт = new Map<number, number>();
  for (const строка of строки) счёт.set(строка.length, (счёт.get(строка.length) ?? 0) + 1);

  let ширина = 0;
  let максимум = -1;
  for (const [длина, сколько] of счёт) {
    if (сколько > максимум) {
      максимум = сколько;
      ширина = длина;
    }
  }
  return ширина;
}

function оценить(раскладка: Раскладка, строки: readonly Ячейка[][]): number {
  if (строки.length === 0) return 0;

  let подошло = 0;
  for (const строка of строки) {
    if (раскладка.колонки.every((роль, i) => ПРОВЕРКИ[роль](строка[i]))) подошло++;
  }
  return подошло / строки.length;
}

/** Роли, из-за которых раскладка не легла, — от частых к редким. Нужно для внятной ошибки. */
function провалившиесяРоли(раскладка: Раскладка, строки: readonly Ячейка[][]): string[] {
  const провалы = new Map<Роль, number>();
  for (const строка of строки) {
    раскладка.колонки.forEach((роль, i) => {
      if (!ПРОВЕРКИ[роль](строка[i])) провалы.set(роль, (провалы.get(роль) ?? 0) + 1);
    });
  }
  return [...провалы.entries()]
    .sort((а, б) => б[1] - а[1])
    .map(([роль, сколько]) => `${роль} (${сколько} из ${строки.length})`);
}

/**
 * Подобрать раскладку под строки файла.
 *
 * Сначала отбираем кандидатов по ширине, затем проверяем типы ячеек. Проверка
 * типов здесь — не формальность: SheetJS молча читает как таблицу и текстовый
 * мусор, и HTML-страницу с ошибкой. Ни одна раскладка на них не ляжет, и файл
 * будет отбит с понятным текстом вместо «импортировано 1 позиция».
 */
export function определитьРаскладку(строки: readonly Ячейка[][]): ВыборРаскладки {
  const проба = выборка(строки);
  const ширина = модальнаяШирина(проба);
  const кандидаты = РАСКЛАДКИ.filter((р) => р.колонки.length === ширина);

  if (кандидаты.length === 0) {
    const известные = РАСКЛАДКИ.map((р) => р.колонки.length).join(' или ');
    throw new ОшибкаПрайса(
      `Не знаю формат: в файле ${ширина} ${склонение(ширина)} в строке, а известные раскладки — ${известные}.`,
      `Пример строки: ${JSON.stringify(проба[0])}. ` +
        'Если клиент поменял набор полей в Форе — добавьте раскладку в src/price/раскладка.ts.',
    );
  }

  const оценки = кандидаты
    .map((раскладка) => ({ раскладка, доля: оценить(раскладка, проба) }))
    .sort((а, б) => б.доля - а.доля);

  const лучшая = оценки[0]!;
  if (лучшая.доля < ПОРОГ_СОВПАДЕНИЯ) {
    throw new ОшибкаПрайса(
      `Ширина строки (${ширина}) совпала с раскладкой «${лучшая.раскладка.имя}», ` +
        `но значения в колонки не укладываются: подошло ${(лучшая.доля * 100).toFixed(1)}% ` +
        `строк выборки при нужных ${ПОРОГ_СОВПАДЕНИЯ * 100}%.`,
      `Не легли колонки: ${провалившиесяРоли(лучшая.раскладка, проба).join(', ')}. ` +
        `Пример строки: ${JSON.stringify(проба[0])}. ` +
        'Похоже, это не прайс или в Форе переставили поля.',
    );
  }

  return лучшая;
}

function склонение(число: number): string {
  const последняя = число % 10;
  const десятки = число % 100;
  if (десятки >= 11 && десятки <= 14) return 'колонок';
  if (последняя === 1) return 'колонка';
  if (последняя >= 2 && последняя <= 4) return 'колонки';
  return 'колонок';
}
